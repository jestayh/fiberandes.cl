  const ATTRS = ['placeholder', 'aria-label', 'alt', 'title', 'data-title', 'data-desc', 'data-tags'];
  const SKIP = '[data-i18n-skip], script, style, noscript';
  const STORE_KEY = 'fa-lang';
  const norm = s => s.replace(/\s+/g, ' ').trim();
  const textOrig = new WeakMap();
  const attrOrig = new WeakMap();
  let lang = 'es';
  let baseTitle = document.title;

  function t(es) {
    return lang === 'en' ? (EN[norm(es)] ?? es) : es;
  }

  function translateText(node) {
    if (!textOrig.has(node)) textOrig.set(node, node.nodeValue);
    const orig = textOrig.get(node);
    if (lang === 'es') {
      if (node.nodeValue !== orig) node.nodeValue = orig;
      return;
    }
    const en = EN[norm(orig)];
    if (!en) return;
    node.nodeValue = orig.match(/^\s*/)[0] + en + orig.match(/\s*$/)[0];
  }

  function translateAttrs(el) {
    let saved = attrOrig.get(el);
    for (const a of ATTRS) {
      if (!el.hasAttribute(a)) continue;
      if (!saved) { saved = {}; attrOrig.set(el, saved); }
      if (!(a in saved)) saved[a] = el.getAttribute(a);
      const value = t(saved[a]);
      if (el.getAttribute(a) !== value) el.setAttribute(a, value);
    }
  }

  // Spanish text in the HTML is the source; originals are remembered so switching back restores them exactly.
  function refresh(root = document.body) {
    if (root.nodeType === 1) translateAttrs(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode: n => (n.nodeType === 1 && n.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT)
    });
    let n;
    while ((n = walker.nextNode())) {
      if (n.nodeType === 3) {
        if (n.nodeValue.trim()) translateText(n);
      } else {
        translateAttrs(n);
      }
    }
  }

  function setLang(next) {
    lang = next === 'en' ? 'en' : 'es';
    document.documentElement.lang = lang;
    document.title = t(baseTitle);
    refresh();
    document.querySelectorAll('.lang-toggle [data-lang]').forEach(b => {
      const on = b.dataset.lang === lang;
      b.classList.toggle('active', on);
      b.setAttribute('aria-pressed', String(on));
    });
    try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* private mode */ }
    const url = new URL(window.location.href);
    if (lang === 'en') url.searchParams.set('lang', 'en');
    else url.searchParams.delete('lang');
    history.replaceState(null, '', url);
    document.dispatchEvent(new CustomEvent('fa:langchange', { detail: { lang } }));
  }

  window.faI18n = { t, refresh, setLang, get lang() { return lang; } };

  document.addEventListener('DOMContentLoaded', () => {
    baseTitle = document.title;
    document.querySelectorAll('.lang-toggle [data-lang]').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));
    let initial = new URLSearchParams(window.location.search).get('lang');
    if (!initial) {
      try { initial = localStorage.getItem(STORE_KEY); } catch (e) { /* private mode */ }
    }
    if (initial === 'en') setLang('en');
  });
